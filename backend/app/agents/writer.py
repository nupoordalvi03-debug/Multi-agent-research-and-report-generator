"""Agent 4 — Report Writer: synthesises ONLY verified claims into the selected report structure.
The LLM cites with [Sxx] markers; references are generated by code from collected sources."""
from __future__ import annotations

import json
import re

from ..models.report import REPORT_TEMPLATES
from ..services.citation_service import apply_citations
from .base import AgentContext, AgentFailure, AgentResult, llm_json

SYSTEM = """You are the Report Writer agent. Write a professional {report_type} in a formal academic tone.
STRICT RULES:
- Use ONLY the verified claims provided. Do not add facts, statistics, studies, authors or dates that are not in the claims.
- Cite sources inline using the given source IDs in square brackets, e.g. "... [S03]" or "[S01][S04]".
  Only cite a source ID listed in that claim's source_ids.
- Claims marked partially_supported or low confidence must be hedged ("limited evidence suggests").
- Contested claims and contradictions must be presented as disagreement, not hidden.
- Evidence gaps must be stated plainly as limitations.
- Distinguish evidence ("Studies report...") from interpretation ("This suggests...").
- Do NOT write a References section; it is generated automatically.
- Use exactly these section headings, in order: {headings}
- Section content: paragraphs separated by a blank line; you may use "- " bullet lists and **bold**. No markdown headings inside content.
Return JSON: {{"title": "...", "sections": [{{"heading": "...", "content": "..."}}]}}"""

REVISE_SYSTEM = SYSTEM + """
You are REVISING an existing draft in response to a critic. Fix every listed issue while keeping
all rules above. Return the complete revised report in the same JSON format."""


def methodology_facts(req: dict, plan: dict, research: dict, verification: dict) -> dict:
    st = research["stats"]
    return {
        "source_target_mode": req["source_mode"], "research_depth": req["depth"],
        "subtopics": [s["title"] for s in plan["subtopics"]],
        "search_queries_run": st["searches"], "unique_candidates": st["candidates"],
        "duplicates_removed": st["duplicates_removed"], "pages_fetched": st["fetched"],
        "fetch_failures": st["fetch_failed"], "sources_used": len(research["sources"]),
        "sources_by_credibility_tier": st["tiers"], "evidence_items": len(research["evidence"]),
        "claims_assessed": len(verification["claims"]),
        "claim_status_counts": verification["stats"],
        "contradictions_found": len(verification["contradictions"]),
        "search_provider": "simulated (demo mode)" if any(s.get("is_demo") for s in research["sources"]) else "TinyFish Search and Fetch APIs",
    }


def _build_input(req, plan, research, verification) -> dict:
    srcs = {s["source_id"]: s for s in research["sources"]}
    claims = [c for c in verification["claims"] if c["include_in_report"]]
    used = sorted({sid for c in claims for sid in c["source_ids"]})
    return {
        "research_question": req["query"], "hypothesis": req.get("hypothesis") or "None provided",
        "subtopics": [{"id": s["id"], "title": s["title"]} for s in plan["subtopics"]],
        "verified_claims": [{k: c[k] for k in ("claim_id", "subtopic_id", "text", "status", "confidence",
                                               "source_ids", "flags", "notes")} for c in claims],
        "contradictions": verification["contradictions"], "evidence_gaps": verification["gaps"],
        "sources": [{"id": s, "title": srcs[s]["title"], "publisher": srcs[s]["publisher"],
                     "date": srcs[s]["publication_date"] or "n.d.", "tier": srcs[s]["credibility_tier"],
                     "type": srcs[s]["source_type"]} for s in used],
        "methodology_facts": methodology_facts(req, plan, research, verification),
    }


def _cite(c: dict) -> str:
    return "".join(f"[{s}]" for s in c["source_ids"][:3])


def _claim_sentence(c: dict) -> str:
    """Claim text with its citation placed before the final full stop."""
    return f"{c['text'].rstrip().rstrip('.')} {_cite(c)}."


def _demo_section(heading: str, data: dict, req: dict) -> str:
    h = heading.lower()
    claims = data["verified_claims"]
    subs = {s["id"]: s["title"] for s in data["subtopics"]}
    mf = data["methodology_facts"]
    if any(k in h for k in ("abstract", "summary")) and "key" not in h:
        return (f"DEMO MODE — this report is generated from simulated sources and is not real research. "
                f"It examines the question: {req['query']} Across {mf['sources_used']} simulated sources, "
                f"{len(claims)} claims were retained after verification {_cite(claims[0])}. Findings are mixed and "
                f"context-dependent, and {len(data['contradictions'])} contradiction(s) between sources were identified.")
    if "introduction" in h or "background" in h:
        return (f"This report investigates {req['query'].rstrip('?').lower()}. The question was decomposed into "
                f"{len(subs)} research dimensions: " + "; ".join(subs.values()) + ".")
    if "research question" in h:
        return req["query"]
    if "hypothesis" in h:
        return data["hypothesis"]
    if any(k in h for k in ("methodology", "scope", "criteria")):
        return (f"A multi-agent pipeline planned {len(subs)} subtopics and ran {mf['search_queries_run']} searches "
                f"using {mf['search_provider']}. {mf['unique_candidates']} unique candidates were identified "
                f"({mf['duplicates_removed']} duplicates removed); {mf['pages_fetched']} pages were fetched and "
                f"{mf['fetch_failures']} failed. Evidence was extracted from {mf['sources_used']} sources and "
                f"{mf['claims_assessed']} claims were assessed by the Verifier.")
    if any(k in h for k in ("benefit", "positive", "agreement")):
        pos = [c for c in claims if c["status"] != "unsupported" and re.search(r"improv|better|benefit", c["text"], re.I)]
        if not pos:
            return "No simulated positive findings were retained by the Verifier."
        return ("Taken together, the positive simulated findings cluster around "
                + "; ".join(sorted({subs[c['subtopic_id']].lower() for c in pos}))
                + f". These benefits are reported by {len({s for c in pos for s in c['source_ids']})} simulated "
                f"source(s) {''.join(f'[{s}]' for s in sorted({s for c in pos for s in c['source_ids']})[:3])}.")
    if any(k in h for k in ("finding", "thematic", "comparative")):
        parts = []
        for sid, title in subs.items():
            mine = [c for c in claims if c["subtopic_id"] == sid]
            if mine:
                parts.append(f"**{title}.** " + " ".join(_claim_sentence(c) for c in mine))
            else:
                parts.append(f"**{title}.** Evidence unavailable for this dimension.")
        return "\n\n".join(parts)
    if any(k in h for k in ("limitation", "risk", "caveat", "gap", "disagreement", "strength")):
        lines = [f"- {x['description']} {''.join(f'[{s}]' for s in x['source_ids'][:2])}" for x in data["contradictions"]]
        lines += [f"- {g['note']} ({g['title']})" for g in data["evidence_gaps"]]
        lines.append("- All sources in this report are simulated; conclusions must not be used.")
        return "\n".join(lines)
    if any(k in h for k in ("discussion", "analysis", "trade-off")):
        contested = [c for c in claims if c["status"] == "contested"]
        return (f"The simulated evidence is mixed: {len(data['contradictions'])} contradiction(s) were detected and "
                f"{len(contested)} claim(s) were marked as contested by the Verifier {_cite(contested[0] if contested else claims[-1])}. "
                f"This pattern suggests that any effect depends on context rather than being uniform.")
    return (f"In simulated evidence, the answer to the research question is conditional rather than absolute "
            f"{_cite(claims[0])}. Real sources are required before drawing conclusions.")


def _finalize(raw: dict, headings: list[str], req: dict, research: dict, verification: dict,
              version: int) -> dict:
    if not isinstance(raw, dict) or not isinstance(raw.get("sections"), list):
        raise AgentFailure("Writer returned JSON without a sections list.")
    got = {str(s.get("heading", "")).strip().lower(): str(s.get("content", "")).strip()
           for s in raw["sections"] if isinstance(s, dict)}
    sections = [{"heading": h, "content": got.get(h.lower(), "")} for h in headings]
    missing = [s["heading"] for s in sections if not s["content"]]
    if len(missing) > len(headings) // 2:
        raise AgentFailure(f"Writer omitted most sections: {', '.join(missing)}")
    for s in sections:
        if not s["content"]:
            s["content"] = "This section could not be generated from the verified evidence."
    srcs = {s["source_id"]: s for s in research["sources"]}
    allowed = {sid for c in verification["claims"] if c["include_in_report"] for sid in c["source_ids"]}
    cit = apply_citations(sections, srcs, allowed, req["citation_style"])
    return {"title": str(raw.get("title") or req["query"])[:250], "sections": sections, "version": version,
            "citation_map": cit["citation_map"], "labels": cit["labels"], "references": cit["references"],
            "removed_citations": cit["removed"], "missing_sections": missing}


async def run(ctx: AgentContext, plan: dict, research: dict, verification: dict) -> AgentResult:
    req = ctx.request
    headings = REPORT_TEMPLATES[req["report_type"]]
    data = _build_input(req, plan, research, verification)
    ctx.report(f"Report Writer is synthesizing {len(data['verified_claims'])} verified claims "
               f"into a {req['report_type']}…", 10)
    if ctx.demo:
        await ctx.demo_pause(4)
        raw = {"title": f"[DEMO] {req['query'].rstrip('?')}: A Simulated {req['report_type']}",
               "sections": [{"heading": h, "content": _demo_section(h, data, req)} for h in headings]}
    else:
        raw = await llm_json(ctx, SYSTEM.format(report_type=req["report_type"], headings=json.dumps(headings)),
                             json.dumps(data), temperature=0.3, purpose="draft v1")
    ctx.report("Report Writer is attaching citations and building references…", 85)
    report = _finalize(raw, headings, req, research, verification, version=1)
    if report["removed_citations"]:
        ctx.report(f"Removed citations to unverified sources: {', '.join(report['removed_citations'])}", level="warning")
    ctx.metrics(sections=len(report["sections"]), citations=len(report["citation_map"]))
    ctx.report(f"Draft v1 written with {len(report['citation_map'])} cited sources.", 95, "success")
    return AgentResult(True, "REPORT_COMPLETED", report, metrics={"citations": len(report["citation_map"])})


def _demo_revise(report: dict, issues: list[dict]) -> dict:
    """DEMO MODE: rule-based revision that removes sentences repeated across sections."""
    seen: set[str] = set()
    sections = []
    for s in report["sections"]:
        paras = []
        for p in s["content"].split("\n\n"):
            kept = []
            for sent in re.split(r"(?<=[.!?])\s+", p):
                key = re.sub(r"\W+", " ", re.sub(r"\[S\d+\]", "", sent).lower()).strip()
                if len(key) > 60 and key in seen:
                    continue
                seen.add(key)
                kept.append(sent)
            if kept:
                paras.append(" ".join(kept))
        sections.append({"heading": s["heading"], "content": "\n\n".join(paras) or s["content"]})
    return {"title": report["title"], "sections": sections}


async def revise(ctx: AgentContext, report: dict, critique: dict, plan: dict, research: dict,
                 verification: dict) -> AgentResult:
    req = ctx.request
    headings = REPORT_TEMPLATES[req["report_type"]]
    issues = critique["issues"]
    ctx.report(f"Report Writer is revising draft v{report['version']} to fix {len(issues)} issue(s)…", 20)
    if ctx.demo:
        await ctx.demo_pause(3)
        raw = _demo_revise(report, issues)
    else:
        data = _build_input(req, plan, research, verification)
        data["current_draft"] = {"title": report["title"], "sections": report["sections"]}
        data["critic_issues"] = issues
        raw = await llm_json(ctx, REVISE_SYSTEM.format(report_type=req["report_type"], headings=json.dumps(headings)),
                             json.dumps(data), temperature=0.2,
                             purpose=f"revise v{report['version']}")
    new = _finalize(raw, headings, req, research, verification, version=report["version"] + 1)
    ctx.report(f"Revision v{new['version']} written.", 95, "success")
    return AgentResult(True, "REPORT_COMPLETED", new)
