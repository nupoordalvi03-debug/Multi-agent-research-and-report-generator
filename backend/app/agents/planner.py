"""Agent 1 — Research Planner: decomposes the question into subtopics and search queries."""
from __future__ import annotations

import json

from ..models.research import DEPTH_LIMITS, ResearchPlan, SubTopic
from ..services.text_util import keywords
from .base import AgentContext, AgentFailure, AgentResult, llm_json

SYSTEM = """You are the Research Planner in a multi-agent research system.
You DO NOT answer the research question. You only design the research plan.
Return JSON with exactly these keys:
{
 "research_question": "precise restatement of the question",
 "key_concepts": ["..."],
 "subtopics": [
   {"title": "...", "rationale": "why this dimension matters",
    "queries": ["search-engine query", "..."],
    "evidence_needed": "what evidence would answer this dimension",
    "source_types": ["peer-reviewed studies", "meta-analyses", "government reports", ...]}
 ],
 "required_source_types": ["..."],
 "evidence_criteria": ["criteria for evidence to be accepted"],
 "scope_notes": "boundaries / assumptions"
}
Search queries must be short (3-10 words), specific, and suitable for a web/academic search engine.
Do not include quotes or site: operators."""


def _validate(raw: dict, req: dict) -> ResearchPlan:
    limits = DEPTH_LIMITS[req["depth"]]
    lo, hi = limits["subtopics"]
    qps = limits["queries_per_subtopic"]
    subs_raw = raw.get("subtopics") or []
    if not isinstance(subs_raw, list) or len(subs_raw) < 2:
        raise AgentFailure("Planner produced fewer than 2 subtopics.")
    seen_q: set[str] = set()
    subtopics: list[SubTopic] = []
    for s in subs_raw[:hi]:
        if not isinstance(s, dict) or not str(s.get("title", "")).strip():
            continue
        qs = []
        for q in s.get("queries") or []:
            q = " ".join(str(q).replace('"', "").split())[:200]
            if q and q.lower() not in seen_q:
                seen_q.add(q.lower())
                qs.append(q)
        if not qs:
            qs = [f"{req['query'][:120]} {s['title']}"]
        subtopics.append(SubTopic(
            id=f"T{len(subtopics) + 1}", title=str(s["title"]).strip()[:150],
            rationale=str(s.get("rationale", ""))[:500], queries=qs[:qps],
            evidence_needed=str(s.get("evidence_needed", ""))[:500],
            source_types=[str(x)[:80] for x in (s.get("source_types") or [])][:6]))
    if len(subtopics) < min(lo, 2):
        raise AgentFailure("Planner output had too few valid subtopics.")
    return ResearchPlan(
        research_question=str(raw.get("research_question") or req["query"])[:500],
        key_concepts=[str(k)[:80] for k in (raw.get("key_concepts") or [])][:12],
        subtopics=subtopics,
        required_source_types=[str(x)[:80] for x in (raw.get("required_source_types") or [])][:10],
        evidence_criteria=[str(x)[:200] for x in (raw.get("evidence_criteria") or [])][:8],
        scope_notes=str(raw.get("scope_notes", ""))[:800])


DEMO_ASPECTS = [
    ("Background and definitions", "definitions background"),
    ("Effects on primary outcomes", "effect study evidence"),
    ("Mechanisms and explanations", "mechanism cognitive explanation"),
    ("Moderating factors and individual differences", "individual differences moderators"),
    ("Limitations, risks and negative findings", "negative effects limitations"),
    ("Practical implications", "practical recommendations"),
    ("Measurement and methodology", "measurement methodology"),
    ("Recent developments", "recent research review"),
]


def _demo_plan(req: dict) -> dict:
    lo, hi = DEPTH_LIMITS[req["depth"]]["subtopics"]
    n = hi if req["depth"] != "Standard" else 5 if lo <= 5 <= hi else hi
    core = " ".join(keywords(req["query"], 4))
    return {
        "research_question": req["query"].strip(),
        "key_concepts": keywords(req["query"] + " " + req.get("hypothesis", ""), 8),
        "subtopics": [{"title": t, "rationale": f"Simulated planning rationale for '{t}'.",
                       "queries": [f"{core} {suffix}", f"{core} {suffix} review"],
                       "evidence_needed": f"Studies or reports addressing {t.lower()}.",
                       "source_types": ["peer-reviewed studies", "institutional reports"]}
                      for t, suffix in DEMO_ASPECTS[:n]],
        "required_source_types": ["peer-reviewed studies", "systematic reviews", "institutional reports"],
        "evidence_criteria": ["Directly addresses a subtopic", "Comes from an identifiable publisher"],
        "scope_notes": "DEMO MODE — plan generated by a rule-based simulator, not an LLM.",
    }


async def run(ctx: AgentContext) -> AgentResult:
    req = ctx.request
    ctx.report("Research Planner is identifying research dimensions…", 10)
    if ctx.demo:
        await ctx.demo_pause(3)
        raw = _demo_plan(req)
    else:
        limits = DEPTH_LIMITS[req["depth"]]
        user = json.dumps({
            "research_question": req["query"],
            "hypothesis": req.get("hypothesis") or None,
            "source_target_mode": req["source_mode"],
            "report_type": req["report_type"],
            "number_of_subtopics": f"{limits['subtopics'][0]}-{limits['subtopics'][1]}",
            "queries_per_subtopic": limits["queries_per_subtopic"],
        }, indent=2)
        ctx.report("Research Planner is asking the LLM to decompose the question…", 30)
        raw = await llm_json(ctx, SYSTEM, user, purpose="plan")  # exactly ONE LLM request
        if not isinstance(raw, dict):
            raise AgentFailure("Planner returned a non-object JSON.")
    plan = _validate(raw, req)
    nq = sum(len(s.queries) for s in plan.subtopics)
    ctx.metrics(subtopics=len(plan.subtopics), queries=nq)
    ctx.report(f"Plan ready: {len(plan.subtopics)} subtopics, {nq} search queries.", 95, "success")
    return AgentResult(True, "PLANNING_COMPLETED", plan.to_dict(),
                       metrics={"subtopics": len(plan.subtopics), "queries": nq})
